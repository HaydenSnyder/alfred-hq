type AgentSeed = Omit<Agent, "origin" | "createdAt" | "updatedAt" | "config" | "stats" | "assignedTaskIds"> &
  Partial<Pick<Agent, "config" | "stats" | "assignedTaskIds">>

function agent(seed: AgentSeed): Agent {
  return {
    ...demo,
    createdAt: daysAgo(120),
    updatedAt: seed.lastActiveAt ?? daysAgo(1),
    assignedTaskIds: [],
    config: {
      temperature: 0.3,
      maxConcurrentTasks: 3,
      approvalRequiredFor: ["external messages", "spending"],
      memoryAccess: seed.scope.kind === "company" ? "company" : "global",
    },
    stats: { tasksCompleted7d: 0, avgLatencyMs: 0, errorRate7d: 0 },
    ...seed,
  }
}

