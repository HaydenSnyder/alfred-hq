/** 30 daily buckets, oldest first. `incidents` maps days-ago → status override. */
function history(seed: number, base: HealthStatus, incidents: Record<number, HealthStatus> = {}): UptimeSample[] {
  const rand = seeded(seed)
  return Array.from({ length: 30 }, (_, i) => {
    const day = 29 - i
    const roll = rand()
    const status: HealthStatus = incidents[day] ?? (base === "healthy" && roll > 0.96 ? "degraded" : base)
    return { at: daysAgo(day), status }
  })
}

